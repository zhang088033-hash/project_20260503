import { AIAgent } from './ai-agents';

type AIModel = 'brainstorm' | 'scriptwriter' | 'postcreator' | 'strategist';

export function generateAIResponse(
  userMessage: string,
  agent: AIAgent,
  conversationHistory: Array<{ role: 'user' | 'assistant'; content: string }> = []
): string {
  const lowerMessage = userMessage.toLowerCase();
  
  switch (agent.id) {
    case 'brainstorm':
      return generateBrainstormResponse(userMessage, conversationHistory);
    case 'scriptwriter':
      return generateScriptResponse(userMessage, conversationHistory);
    case 'postcreator':
      return generatePostResponse(userMessage, conversationHistory);
    case 'strategist':
      return generateStrategyResponse(userMessage, conversationHistory);
    default:
      return generateDefaultResponse(userMessage);
  }
}

